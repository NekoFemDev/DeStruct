package arm64lift

// cheader.go generates a C header describing the IL2CPP classes an
// offset dump carries, for the --emit-il2cpp-c output mode: one
// typedef'd struct per class whose field positions match the byte
// offsets the decompiled code actually uses, plus a _Static_assert per
// field so a layout mismatch is a compile error rather than a silent
// wrong read. Reference-typed fields (strings, other classes, generic
// containers) are void* - their pointee layout isn't in an offset
// dump - and value-typed primitives use their C equivalent.
//
// The struct and field names are sanitized with the same
// SanitizeCType used by RewriteForIL2CPP's casts, so the generated C
// body's "((Axlebolt_Bolt_Protobuf_PlayerAchievement*)this)->id_"
// refers to exactly the typedef this header declares.

import (
	"fmt"
	"sort"
	"strings"
)

// SanitizeCType turns a dump's dotted class or field name into a valid
// C identifier: every character outside [A-Za-z0-9_] becomes '_', a
// leading digit is prefixed with '_'. Names that are already valid are
// returned unchanged.
func SanitizeCType(name string) string {
	var b strings.Builder
	for i, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r == '_':
			b.WriteRune(r)
		case r >= '0' && r <= '9':
			if i == 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "il2cpp_object"
	}
	return b.String()
}

// cFieldType maps an IL2CPP metadata type name to its C spelling and
// storage size in bytes. Reference types (anything not a known value
// type) are pointers.
func cFieldType(typ string) (cType string, size uint64) {
	switch typ {
	case "bool":
		return "uint8_t", 1
	case "byte":
		return "uint8_t", 1
	case "sbyte":
		return "int8_t", 1
	case "char":
		return "uint16_t", 2
	case "short":
		return "int16_t", 2
	case "ushort":
		return "uint16_t", 2
	case "int":
		return "int32_t", 4
	case "uint":
		return "uint32_t", 4
	case "float":
		return "float", 4
	case "long":
		return "int64_t", 8
	case "ulong":
		return "uint64_t", 8
	case "double":
		return "double", 8
	case "string", "object":
		return "void*", 8
	}
	// Arrays, generic instantiations and other classes are IL2CPP
	// object references in memory.
	return "void*", 8
}

// Deprecated: GenerateIL2CPPHeader is the legacy header generator for
// the removed --emit-il2cpp-c mode. The unified pseudo-C renderer does
// not emit class layouts, and the pipeline no longer calls this.
//
// GenerateIL2CPPHeader renders the header for every class in db that
// has at least one instance field. Classes and fields are emitted in a
// deterministic (name / offset) order so regenerating the header for
// the same dump is byte-identical.
func GenerateIL2CPPHeader(db *OffsetDB) []byte {
	var b strings.Builder
	b.WriteString("/*\n")
	b.WriteString(" * IL2CPP class layout header generated by DeStruct (--emit-il2cpp-c).\n")
	b.WriteString(" *\n")
	b.WriteString(" * Field positions match the byte offsets in the loaded offset dump, measured\n")
	b.WriteString(" * from the managed object's own address (the 16-byte IL2CPP object header\n")
	b.WriteString(" * included), which is the displacement decompiled ldr/str instructions use.\n")
	b.WriteString(" * Reference-typed fields are void*; primitives use fixed-width C types.\n")
	b.WriteString(" */\n")
	b.WriteString("#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n")

	classes := db.Classes()
	sort.Slice(classes, func(i, j int) bool { return classes[i].Name < classes[j].Name })

	usedNames := make(map[string]bool)
	for _, c := range classes {
		if len(c.Fields) == 0 {
			continue
		}
		cname := SanitizeCType(c.Name)
		if usedNames[cname] {
			cname = fmt.Sprintf("%s_td%d", cname, c.TypeDefIndex)
		}
		usedNames[cname] = true

		fields := append([]FieldRef(nil), c.Fields...)
		sort.Slice(fields, func(i, j int) bool {
			if fields[i].Offset != fields[j].Offset {
				return fields[i].Offset < fields[j].Offset
			}
			return fields[i].Name < fields[j].Name
		})

		fmt.Fprintf(&b, "/* %s (TypeDefIndex: %d) */\n", c.Name, c.TypeDefIndex)
		fmt.Fprintf(&b, "typedef struct %s {\n", cname)

		fieldNames := make(map[string]bool)
		cursor := uint64(0)
		padSeq := 0
		type fieldAssert struct {
			name string
			off  uint64
		}
		var asserts []fieldAssert
		for _, f := range fields {
			if f.Offset < cursor {
				// Overlapping declarations (a derived class dump that
				// repeats a base field, say) can't be laid out as a
				// struct; skip rather than emit a wrong member.
				fmt.Fprintf(&b, "    /* skipped overlapping %s at 0x%X */\n", f.Name, f.Offset)
				continue
			}
			if f.Offset > cursor {
				fmt.Fprintf(&b, "    uint8_t _pad%d[0x%X]; /* 0x%X..0x%X */\n", padSeq, f.Offset-cursor, cursor, f.Offset)
				padSeq++
			}
			fname := SanitizeCType(f.Name)
			if fieldNames[fname] {
				fname = fmt.Sprintf("%s_%d", fname, f.Offset)
			}
			fieldNames[fname] = true

			ctype, size := cFieldType(f.Type)
			fmt.Fprintf(&b, "    %s %s; /* 0x%X %s */\n", ctype, fname, f.Offset, f.Type)
			asserts = append(asserts, fieldAssert{fname, f.Offset})
			cursor = f.Offset + size
		}
		fmt.Fprintf(&b, "} %s;\n", cname)
		for _, a := range asserts {
			fmt.Fprintf(&b, "_Static_assert(offsetof(%s, %s) == 0x%X, \"%s.%s offset\");\n", cname, a.name, a.off, cname, a.name)
		}
		b.WriteString("\n")
	}
	return []byte(b.String())
}
