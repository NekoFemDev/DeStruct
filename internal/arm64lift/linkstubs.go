package arm64lift

// linkstubs.go generates a stubs.c translation unit for the unresolved
// extern symbols in a directory of decompiled .c files. It is a
// post-processing step: the decompiler itself only prints
// "extern uint64_t name();" declarations, so the final link needs one
// definition per missing symbol.
//
// The generator deliberately classifies symbols by their declaration
// syntax:
//
//   - "extern uint64_t foo();"   -> function stub
//   - "extern uint64_t foo;"     -> dummy variable
//
// Generated call sites use an unprototyped declaration, so every
// function stub can safely use the common eight-uint64_t AAPCS64
// signature. Known libc wrappers forward the first N arguments to the
// real libc function; everything else returns 0.

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// LinkStubResult reports what GenerateLinkStubs found and emitted.
type LinkStubResult struct {
	Path             string
	LibcWrappers     []string
	GenericFunctions []string
	Variables        []string
	Defined          []string
	AddedMain        bool
}

var (
	// extern uint64_t ext_memmove();
	linkExternFuncRe = regexp.MustCompile(`(?m)^\s*extern\s+[A-Za-z_][A-Za-z0-9_]*\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*\)\s*;`)
	// extern uint64_t ext_some_global;
	linkExternVarRe = regexp.MustCompile(`(?m)^\s*extern\s+[A-Za-z_][A-Za-z0-9_]*\s+([A-Za-z_][A-Za-z0-9_]*)\s*;`)
	// uint64_t sub_123(...) {  /  int main(void) {
	linkDefRe = regexp.MustCompile(`(?m)^\s*(?:uint64_t|int|void)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\([^;{}]*\)\s*\{`)
	// any identifier followed by "(" after extern declarations are stripped
	linkCallRe = regexp.MustCompile(`\b([A-Za-z_][A-Za-z0-9_]*)\s*\(`)
)

// GenerateLinkStubsDir walks dir for .c files (recursively), skips the
// output file itself and stubs.c, and writes one stubs.c to outPath. An
// empty outPath defaults to <dir>/stubs.c.
func GenerateLinkStubsDir(dir, outPath string) (*LinkStubResult, error) {
	if outPath == "" {
		outPath = filepath.Join(dir, "stubs.c")
	}
	absOut, err := filepath.Abs(outPath)
	if err != nil {
		return nil, err
	}
	var files []string
	err = filepath.WalkDir(dir, func(path string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		if !strings.EqualFold(filepath.Ext(path), ".c") {
			return nil
		}
		absPath, err := filepath.Abs(path)
		if err != nil {
			return err
		}
		if absPath == absOut || filepath.Base(path) == "stubs.c" {
			return nil
		}
		files = append(files, path)
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	return GenerateLinkStubs(files, outPath)
}

// GenerateLinkStubs scans files, finds extern declarations without a
// matching definition in any of those files, and writes a stubs.c that
// defines every missing symbol. A dummy main is added unless a main
// definition was already found.
func GenerateLinkStubs(files []string, outPath string) (*LinkStubResult, error) {
	externFuncs := make(map[string]bool)
	externVars := make(map[string]bool)
	defined := make(map[string]bool)
	called := make(map[string]bool)

	for _, path := range files {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", path, err)
		}
		content := string(data)

		for _, m := range linkExternFuncRe.FindAllStringSubmatch(content, -1) {
			externFuncs[m[1]] = true
		}
		for _, m := range linkExternVarRe.FindAllStringSubmatch(content, -1) {
			externVars[m[1]] = true
		}
		for _, m := range linkDefRe.FindAllStringSubmatch(content, -1) {
			defined[m[1]] = true
		}

		// Remove the extern declarations before collecting call names:
		// "extern uint64_t foo();" itself contains "foo(" and would
		// otherwise make every missing symbol look called.
		stripped := linkExternFuncRe.ReplaceAllString(content, "")
		stripped = linkExternVarRe.ReplaceAllString(stripped, "")
		for _, m := range linkCallRe.FindAllStringSubmatch(stripped, -1) {
			called[m[1]] = true
		}
	}

	result := &LinkStubResult{Path: outPath}
	missingFuncs := make([]string, 0)
	missingVars := make([]string, 0)
	for name := range externFuncs {
		if defined[name] {
			continue
		}
		if name == "main" {
			continue
		}
		missingFuncs = append(missingFuncs, name)
	}
	for name := range externVars {
		if defined[name] || externFuncs[name] {
			continue
		}
		missingVars = append(missingVars, name)
	}
	sort.Strings(missingFuncs)
	sort.Strings(missingVars)
	for name := range defined {
		result.Defined = append(result.Defined, name)
	}
	sort.Strings(result.Defined)

	var b strings.Builder
	b.WriteString("/*\n")
	b.WriteString(" * Link stubs generated by DeStruct.\n")
	b.WriteString(" *\n")
	b.WriteString(" * Every unresolved extern from the decompiled translation units is\n")
	b.WriteString(" * defined here. Libc-backed symbols forward their first arguments to\n")
	b.WriteString(" * the real libc function; everything else is a linkable no-op.\n")
	b.WriteString(" */\n")
	b.WriteString("#define _GNU_SOURCE\n")
	b.WriteString("#include <stdint.h>\n")
	b.WriteString("#include <stddef.h>\n")
	b.WriteString("#include <stdlib.h>\n")
	b.WriteString("#include <string.h>\n")
	b.WriteString("#include <stdio.h>\n")
	b.WriteString("#include <stdarg.h>\n")
	b.WriteString("#include <time.h>\n")
	b.WriteString("#include <wchar.h>\n")
	b.WriteString("#include <syslog.h>\n\n")

	if missingContains(missingFuncs, "ext___errno") {
		b.WriteString("/* ext___errno() must return a writable pointer; generated code\n")
		b.WriteString(" * calls it and dereferences the result. */\n")
		b.WriteString("static uint32_t eni_errno_storage;\n\n")
	}

	if len(missingFuncs) > 0 {
		b.WriteString("/* libc-backed wrappers */\n")
		wroteLibc := false
		for _, name := range missingFuncs {
			if body, ok := libcStubBody(name); ok {
				writeFunctionStub(&b, name, body)
				result.LibcWrappers = append(result.LibcWrappers, name)
				wroteLibc = true
			}
		}
		if !wroteLibc {
			b.WriteString("/* none */\n")
		}
		b.WriteString("\n/* generic stubs */\n")
		for _, name := range missingFuncs {
			if _, ok := libcStubBody(name); ok {
				continue
			}
			writeFunctionStub(&b, name, genericStubBody(name))
			result.GenericFunctions = append(result.GenericFunctions, name)
		}
	}

	if len(missingVars) > 0 {
		b.WriteString("\n/* variable stubs */\n")
		for _, name := range missingVars {
			fmt.Fprintf(&b, "uint64_t %s; /* dummy definition */\n", name)
			result.Variables = append(result.Variables, name)
		}
	}

	if !defined["main"] {
		b.WriteString("\n/* entry point for the dummy executable */\n")
		b.WriteString("int main(void)\n{\n    return 0;\n}\n")
		result.AddedMain = true
	}

	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		return nil, fmt.Errorf("write %s: %w", outPath, err)
	}
	return result, nil
}

func missingContains(names []string, want string) bool {
	for _, name := range names {
		if name == want {
			return true
		}
	}
	return false
}

const linkStubParams = "uint64_t a0, uint64_t a1, uint64_t a2, uint64_t a3, uint64_t a4, uint64_t a5, uint64_t a6, uint64_t a7"

func writeFunctionStub(b *strings.Builder, name, body string) {
	fmt.Fprintf(b, "uint64_t %s(%s)\n{\n%s\n}\n\n", name, linkStubParams, body)
}

// libcStubBody maps a generated ext_* name to a best-effort wrapper
// around the real libc function. ok=false means "generic zero stub".
func libcStubBody(name string) (string, bool) {
	switch name {
	case "ext_memmove":
		return "    return (uint64_t)memmove((void*)(uintptr_t)a0, (const void*)(uintptr_t)a1, (size_t)a2);", true
	case "ext_memcmp":
		return "    return (uint64_t)memcmp((const void*)(uintptr_t)a0, (const void*)(uintptr_t)a1, (size_t)a2);", true
	case "ext_memcpy":
		return "    return (uint64_t)memcpy((void*)(uintptr_t)a0, (const void*)(uintptr_t)a1, (size_t)a2);", true
	case "ext_memset":
		return "    return (uint64_t)memset((void*)(uintptr_t)a0, (int)a1, (size_t)a2);", true
	case "ext_strlen":
		return "    return (uint64_t)strlen((const char*)(uintptr_t)a0);", true
	case "ext_wcslen":
		return "    return (uint64_t)wcslen((const wchar_t*)(uintptr_t)a0);", true
	case "ext_strerror_r":
		return "    return (uint64_t)strerror_r((int)a0, (char*)(uintptr_t)a1, (size_t)a2);", true
	case "ext_clock_gettime":
		return "    return (uint64_t)clock_gettime((clockid_t)a0, (struct timespec*)(uintptr_t)a1);", true
	case "ext_openlog":
		return "    openlog((const char*)(uintptr_t)a0, (int)a1, (int)a2);\n    return 0;", true
	case "ext_snprintf":
		// The generated call site uses an unprototyped declaration, so
		// integer/pointer varargs arrive in a3..a7. This forwards five
		// integer-class varargs; floating-point varargs would need a
		// real va_list and are outside this link-only stub's scope.
		return "    return (uint64_t)snprintf((char*)(uintptr_t)a0, (size_t)a1, (const char*)(uintptr_t)a2, a3, a4, a5, a6, a7);", true
	case "ext_abort":
		return "    abort();\n    return 0;", true
	case "ext___errno":
		return "    return (uint64_t)(uintptr_t)&eni_errno_storage;", true
	}
	return "", false
}

func genericStubBody(name string) string {
	if name == "ext_vasprintf" {
		return "    return (uint64_t)-1; // variadic libc function: link-only stub"
	}
	if name == "ext_vfprintf" {
		return "    return 0; // variadic libc function: link-only stub"
	}
	return "    return 0;"
}
