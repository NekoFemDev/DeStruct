// maxELFImageSize bounds the reconstructed load image so a pathological
// ET_EXEC with high virtual addresses cannot make `elf --decompile` write
// a huge blob.
const maxELFImageSize = 512 << 20

const shtNobits = 8

// writeImageRelocations emits image_relocs.c: a constructor that applies
// .rela.dyn R_AARCH64_RELATIVE entries to the reconstructed image using
// host pointers. Data targets are rebased into eni_image; targets that are
// decompiled function entries become &sub_<addr> so vtables, init_array and
// function-pointer tables call the lifted C functions.
func writeImageRelocations(
	ctx context.Context,
	elf *native.ELFParser,
	dir string,
	base, size uint64,
	candidates []funcCandidate,
) (int, error) {
	if size == 0 {
		return 0, nil
	}
	funcByAddr := make(map[uint64]string, len(candidates))
	for _, c := range candidates {
		if isCIdent(c.name) {
			funcByAddr[c.addr] = c.name
		}
	}
	imageEnd := base + size
	if imageEnd < base {
		return 0, nil
	}

	type patch struct {
		slot uint64
		rhs  string
		cond string
	}
	var patches []patch
	usedFuncs := make(map[string]bool)
	usedExt := make(map[string]bool)
	dynsyms := elf.DynamicSymbols(ctx)
	for _, rel := range elf.DynamicRelocations(ctx) {
		slot := rel.Offset
		if slot < base || slot+8 > imageEnd {
			continue
		}
		relType := uint32(rel.Info & 0xffffffff)
		var rhs, cond string
		switch relType {
		case 1027: // R_AARCH64_RELATIVE
			target := uint64(rel.Addend)
			if name, ok := funcByAddr[target]; ok {
				rhs = "(uint64_t)(uintptr_t)&" + name
				cond = "&" + name
				usedFuncs[name] = true
			} else if target >= base && target < imageEnd {
				rhs = fmt.Sprintf("(uint64_t)(uintptr_t)(eni_image + 0x%x)", target-base)
			} else {
				rhs = fmt.Sprintf("(uint64_t)0x%x", target)
			}
		case 1025, 257: // R_AARCH64_GLOB_DAT / R_AARCH64_ABS64
			idx := rel.SymbolIndex()
			if int(idx) >= len(dynsyms) {
				continue
			}
			sym := dynsyms[idx]
			if sym.Name == "" || sym.Info&0xf != 2 { // STT_FUNC
				continue
			}
			name := arm64lift.ExternalCName(sym.Name)
			if !isCIdent(name) {
				continue
			}
			rhs = "(uint64_t)(uintptr_t)&" + name
			usedExt[name] = true
		default:
			continue
		}
		patches = append(patches, patch{slot: slot - base, rhs: rhs, cond: cond})
	}
	if len(patches) == 0 {
		return 0, nil
	}
	sort.Slice(patches, func(i, j int) bool { return patches[i].slot < patches[j].slot })

	var b strings.Builder
	b.WriteString("/* Auto-generated by DeStruct: apply the original ELF's\n")
	b.WriteString(" * R_AARCH64_RELATIVE relocations to the eni_image blob. */\n")
	b.WriteString("#include <stdint.h>\n\nextern unsigned char eni_image[];\n")
	for name := range usedFuncs {
		fmt.Fprintf(&b, "extern uint64_t %s() __attribute__((weak));\n", name)
	}
	for name := range usedExt {
		fmt.Fprintf(&b, "extern uint64_t %s();\n", name)
	}
	b.WriteString("\nstatic void __attribute__((constructor)) eni_apply_image_relocs(void)\n{\n")
	for _, p := range patches {
		if p.cond != "" {
			fmt.Fprintf(&b, "    if (%s) *(uint64_t*)(eni_image + 0x%x) = %s;\n", p.cond, p.slot, p.rhs)
		} else {
			fmt.Fprintf(&b, "    *(uint64_t*)(eni_image + 0x%x) = %s;\n", p.slot, p.rhs)
		}
	}
	b.WriteString("}\n")
	return len(patches), os.WriteFile(filepath.Join(dir, "image_relocs.c"), []byte(b.String()), 0o644)
}

func isCIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}

// writeELFImage writes image.bin (the original ELF's allocated section
// contents, gaps zero-filled) and image.c (an .incbin wrapper defining
// eni_image) into dir. Generated C references absolute addresses through
// ENI_ADDR so data reads/writes land in this reconstructed image instead
// of an unmapped host address.
func writeELFImage(elf *native.ELFParser, dir string) (base, size uint64, err error) {
	minAddr := ^uint64(0)
	maxAddr := uint64(0)
	for _, s := range elf.Sections {
		if s.Flags&native.SHF_ALLOC == 0 || s.Size == 0 {
			continue
		}
		if s.Addr < minAddr {
			minAddr = s.Addr
		}
		end := s.Addr + s.Size
		if end < s.Addr {
			continue
		}
		if end > maxAddr {
			maxAddr = end
		}
	}
	if minAddr == ^uint64(0) || maxAddr <= minAddr {
		return 0, 0, nil
	}

	// PIE/DSO addresses are link-time offsets from zero; for ordinary
	// low-address executables mapping from zero too avoids a base constant
	// that user code might index below. High-address ET_EXEC keeps its
	// lowest section address (rounded down) instead.
	base = 0
	if elf.Header.Type != native.ET_DYN && maxAddr > maxELFImageSize {
		base = minAddr &^ 0xfff
	}
	size = maxAddr - base
	if size == 0 || size > maxELFImageSize {
		return 0, 0, fmt.Errorf("ELF image span 0x%x exceeds the %d MiB limit", size, maxELFImageSize>>20)
	}

	img := make([]byte, size)
	// A PIE's first PT_LOAD includes the ELF header and program header
	// table at virtual address 0. The section-based copy below starts at
	// the first section (.interp usually), so copy the prefix too.
	if base == 0 && elf.Header.Type == native.ET_DYN {
		n := minAddr
		if n > uint64(len(elf.Data)) {
			n = uint64(len(elf.Data))
		}
		copy(img, elf.Data[:n])
	}
	for _, s := range elf.Sections {
		if s.Flags&native.SHF_ALLOC == 0 || s.Size == 0 || s.Addr < base {
			continue
		}
		off := s.Addr - base
		if off >= size {
			continue
		}
		n := s.Size
		if off+n > size {
			n = size - off
		}
		if s.Type == shtNobits {
			continue
		}
		if s.Offset > uint64(len(elf.Data)) || s.Offset+s.Size > uint64(len(elf.Data)) {
			continue
		}
		copy(img[off:off+n], elf.Data[s.Offset:s.Offset+n])
	}

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, 0, err
	}
	binPath := filepath.Join(dir, "image.bin")
	if err := os.WriteFile(binPath, img, 0o644); err != nil {
		return 0, 0, err
	}

	abs, err := filepath.Abs(binPath)
	if err != nil {
		return 0, 0, err
	}
	abs = strings.ReplaceAll(abs, `\`, `\\`)
	abs = strings.ReplaceAll(abs, `"`, `\"`)
	cSrc := fmt.Sprintf(`/* Auto-generated by DeStruct: original ELF load image.
 * The decompiled C uses ENI_ADDR(orig_va) to access this blob.
 */
__asm__(
    ".section .data\n"
    ".balign 4096\n"
    ".global eni_image\n"
    "eni_image:\n"
    ".incbin \"%s\"\n"
    ".byte 0\n"
);
`, abs)
	if err := os.WriteFile(filepath.Join(dir, "image.c"), []byte(cSrc), 0o644); err != nil {
		return 0, 0, err
	}
	return base, size, nil
}
