// writeTLSSupport emits eni_tls.c: the zero-initialized TLS block that
// lifted TPIDR_EL0 accesses index through ENI_TLS_BASE. Keeping it in its
// own translation unit means every split function can declare it extern
// while the decompiled program and the verification driver share one
// definition.
func writeTLSSupport(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	src := `/* Auto-generated by DeStruct: zero-initialized TLS block used by
 * lifted TPIDR_EL0 (thread pointer) accesses. The base sits in the middle
 * so both positive and negative TLS offsets remain in bounds. */
#include <stdint.h>

unsigned char eni_tls[0x10000];

/* Callee-saved context saved by a jump-table dispatcher and reloaded by
 * an outlined entry. Index i corresponds to x(19+i). */
uint64_t eni_outlined_ctx[10];

/* Shared stack frame used when an outlined entry inherits its
 * dispatcher's sp/x29. */
unsigned char eni_outlined_stack[0x10000];
uintptr_t eni_outlined_sp;
uintptr_t eni_outlined_fp;

__attribute__((constructor)) static void eni_outlined_stack_init(void)
{
    eni_outlined_sp = (uintptr_t)(eni_outlined_stack + 0x8000);
}
`
	return os.WriteFile(filepath.Join(dir, "eni_tls.c"), []byte(src), 0o644)
}

// writeTargetResolver emits eni_targets.c: the address-to-C resolver used
// by indirect jump-table dispatches. Without it a dispatcher would call
// raw image bytes and any saved outlined register/stack context would
// never be consumed.
func writeTargetResolver(
	dir string,
	candidates []funcCandidate,
	imageBase, imageSize uint64,
) error {
	type target struct {
		addr uint64
		name string
	}
	var targets []target
	for _, c := range candidates {
		name := arm64lift.FunctionCName(c.name)
		if name == "" || !isCIdent(name) {
			continue
		}
		targets = append(targets, target{addr: c.addr, name: name})
	}
	if len(targets) == 0 {
		return nil
	}
	sort.Slice(targets, func(i, j int) bool { return targets[i].addr < targets[j].addr })

	var b strings.Builder
	b.WriteString("/* Auto-generated by DeStruct: indirect target resolver. */\n")
	b.WriteString("#include <stdint.h>\n\n")
	for _, t := range targets {
		fmt.Fprintf(&b, "extern uint64_t %s();\n", t.name)
	}
	b.WriteString("\ntypedef struct { uintptr_t addr; void *fn; } eni_target_entry;\n")
	b.WriteString("static const eni_target_entry eni_targets[] = {\n")
	for _, t := range targets {
		fmt.Fprintf(&b, "    { 0x%xULL, (void *)%s },\n", t.addr, t.name)
	}
	b.WriteString("};\n\n")
	if imageSize > 0 {
		b.WriteString("extern unsigned char eni_image[];\n")
		fmt.Fprintf(&b, "#define ENI_RESOLVE_IMAGE_BASE ((uintptr_t)0x%x)\n", imageBase)
		fmt.Fprintf(&b, "#define ENI_RESOLVE_IMAGE_SIZE ((uintptr_t)0x%x)\n\n", imageSize)
	}
	b.WriteString(`static uintptr_t eni_target_va(uintptr_t addr)
{
`)
	if imageSize > 0 {
		b.WriteString(`    uintptr_t start = (uintptr_t)eni_image;
    if (addr >= start && addr < start + ENI_RESOLVE_IMAGE_SIZE) {
        return ENI_RESOLVE_IMAGE_BASE + (addr - start);
    }
`)
	}
	b.WriteString(`    return addr;
}

uint64_t ENI_TARGET(uintptr_t addr)
{
    unsigned lo = 0, hi = sizeof(eni_targets) / sizeof(eni_targets[0]);
    addr = eni_target_va(addr);
    while (lo < hi) {
        unsigned mid = lo + (hi - lo) / 2;
        if (eni_targets[mid].addr < addr) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if (lo < sizeof(eni_targets) / sizeof(eni_targets[0]) && eni_targets[lo].addr == addr) {
        return (uint64_t)(uintptr_t)eni_targets[lo].fn;
    }
    return (uint64_t)addr;
}
`)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "eni_targets.c"), []byte(b.String()), 0o644)
}

// writeImageRelocations emits image_relocs.c: a constructor that applies
// .rela.dyn R_AARCH64_RELATIVE entries to the reconstructed image using
// host pointers. Data targets are rebased into eni_image; targets that are
// decompiled function entries become &sub_<addr> so vtables, init_array and
// function-pointer tables call the lifted C functions.
func writeImageRelocations(
	ctx context.Context,
	elf *native.ELFParser,
	dir string,
	base, size uint64,
	candidates []funcCandidate,
) (int, error) {
	if size == 0 {
		return 0, nil
	}
	funcByAddr := make(map[uint64]string, len(candidates))
	for _, c := range candidates {
		if isCIdent(c.name) {
			funcByAddr[c.addr] = c.name
		}
	}
	imageEnd := base + size
	if imageEnd < base {
		return 0, nil
	}

	type patch struct {
		slot uint64
		rhs  string
		cond string
	}
	var patches []patch
	usedFuncs := make(map[string]bool)
	usedExt := make(map[string]bool)
	dynsyms := elf.DynamicSymbols(ctx)
	for _, rel := range elf.DynamicRelocations(ctx) {
		slot := rel.Offset
		if slot < base || slot+8 > imageEnd {
			continue
		}
		relType := uint32(rel.Info & 0xffffffff)
		var rhs, cond string
		switch relType {
		case 1027: // R_AARCH64_RELATIVE
			target := uint64(rel.Addend)
			if name, ok := funcByAddr[target]; ok {
				rhs = "(uint64_t)(uintptr_t)&" + name
				cond = "&" + name
				usedFuncs[name] = true
			} else if target >= base && target < imageEnd {
				rhs = fmt.Sprintf("(uint64_t)(uintptr_t)(eni_image + 0x%x)", target-base)
			} else {
				rhs = fmt.Sprintf("(uint64_t)0x%x", target)
			}
		case 1025, 257: // R_AARCH64_GLOB_DAT / R_AARCH64_ABS64
			idx := rel.SymbolIndex()
			if int(idx) >= len(dynsyms) {
				continue
			}
			sym := dynsyms[idx]
			if sym.Name == "" || sym.Info&0xf != 2 { // STT_FUNC
				continue
			}
			name := arm64lift.ExternalCName(sym.Name)
			if !isCIdent(name) {
				continue
			}
			rhs = "(uint64_t)(uintptr_t)&" + name
			usedExt[name] = true
		default:
			continue
		}
		patches = append(patches, patch{slot: slot - base, rhs: rhs, cond: cond})
	}
	if len(patches) == 0 {
		return 0, nil
	}
	sort.Slice(patches, func(i, j int) bool { return patches[i].slot < patches[j].slot })

	var b strings.Builder
	b.WriteString("/* Auto-generated by DeStruct: apply the original ELF's\n")
	b.WriteString(" * R_AARCH64_RELATIVE relocations to the eni_image blob. */\n")
	b.WriteString("#include <stdint.h>\n\nextern unsigned char eni_image[];\n")
	for name := range usedFuncs {
		fmt.Fprintf(&b, "extern uint64_t %s() __attribute__((weak));\n", name)
	}
	for name := range usedExt {
		fmt.Fprintf(&b, "extern uint64_t %s();\n", name)
	}
	b.WriteString("\nstatic void __attribute__((constructor)) eni_apply_image_relocs(void)\n{\n")
	for _, p := range patches {
		if p.cond != "" {
			fmt.Fprintf(&b, "    if (%s) *(uint64_t*)(eni_image + 0x%x) = %s;\n", p.cond, p.slot, p.rhs)
		} else {
			fmt.Fprintf(&b, "    *(uint64_t*)(eni_image + 0x%x) = %s;\n", p.slot, p.rhs)
		}
	}
	b.WriteString("}\n")
	return len(patches), os.WriteFile(filepath.Join(dir, "image_relocs.c"), []byte(b.String()), 0o644)
}

func isCIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return true
}

// writeELFImage writes image.bin (the original ELF's allocated section
// contents, gaps zero-filled) and image.c (an .incbin wrapper defining
// eni_image) into dir. Generated C references absolute addresses through
// ENI_ADDR so data reads/writes land in this reconstructed image instead
// of an unmapped host address.
func writeELFImage(elf *native.ELFParser, dir string) (base, size uint64, err error) {
	base, img, err := elf.LoadImage()
	if err != nil || len(img) == 0 {
		return 0, 0, err
	}
	size = uint64(len(img))

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, 0, err
	}
	binPath := filepath.Join(dir, "image.bin")
	if err := os.WriteFile(binPath, img, 0o644); err != nil {
		return 0, 0, err
	}

	abs, err := filepath.Abs(binPath)
	if err != nil {
		return 0, 0, err
	}
	abs = strings.ReplaceAll(abs, `\`, `\\`)
	abs = strings.ReplaceAll(abs, `"`, `\"`)
	cSrc := fmt.Sprintf(`/* Auto-generated by DeStruct: original ELF load image.
 * The decompiled C uses ENI_ADDR(orig_va) to access this blob.
 */
__asm__(
    ".section .data\n"
    ".balign 4096\n"
    ".global eni_image\n"
    "eni_image:\n"
    ".incbin \"%s\"\n"
    ".byte 0\n"
);
`, abs)
	if err := os.WriteFile(filepath.Join(dir, "image.c"), []byte(cSrc), 0o644); err != nil {
		return 0, 0, err
	}
	return base, size, nil
}
